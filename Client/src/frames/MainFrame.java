    /**
     * This method makes buttons enable related with access level
     * @param access assigned access level, recieved from the server
     */
    private void initMenus(int access) {
        modifyBtn.setVisible(false);
        modifyBtn.setEnabled(false);
        createNewBtn.setVisible(false);
        createNewBtn.setEnabled(false);
        removeFileBtn.setVisible(false);
        removeFileBtn.setEnabled(false);
        uploadFileBtn.setVisible(false);
        uploadFileBtn.setEnabled(false);

        modifyFileMenuBtn.setVisible(false);
        createNewFileMenuBtn.setVisible(false);
        removeFileMenuBtn.setVisible(false);
        uploadFileBtn.setVisible(false);
        uploadFileMenuBtn.setVisible(false);

        switch (access) {
            case 1 -> {
                // OPEN + DOWNLOAD
            }
            case 2 -> {
                // OPER + DOWNLOAD + MODIFY
                modifyBtn.setVisible(true);
                modifyBtn.setEnabled(true);
                modifyFileMenuBtn.setVisible(true);
            }
            case 3 -> {
                // OPEN + DOWNLOAD + MODIFY + CREATE/UPLOAD
                modifyBtn.setVisible(true);
                modifyBtn.setEnabled(true);
                createNewBtn.setVisible(true);
                createNewBtn.setEnabled(true);
                uploadFileBtn.setVisible(true);
                uploadFileBtn.setEnabled(true);

                modifyFileMenuBtn.setVisible(true);
                createNewFileMenuBtn.setVisible(true);
                uploadFileBtn.setVisible(true);
                uploadFileMenuBtn.setVisible(true);
            }
            case 4 -> {
                // OPEN + DOWNLOAD + MODIFY + CREATE/UPLOAD + REMOVE
                modifyBtn.setVisible(true);
                modifyBtn.setEnabled(true);
                createNewBtn.setVisible(true);
                createNewBtn.setEnabled(true);
                removeFileBtn.setVisible(true);
                removeFileBtn.setEnabled(true);
                uploadFileBtn.setVisible(true);
                uploadFileBtn.setEnabled(true);

                modifyFileMenuBtn.setVisible(true);
                createNewFileMenuBtn.setVisible(true);
                removeFileMenuBtn.setVisible(true);
                uploadFileBtn.setVisible(true);
                uploadFileMenuBtn.setVisible(true);
            }
            default -> {
                // OPEN + DOWNLOAD
            }
        }
    }

    private void handleOpening(String value) {
        if (!value.contains(".")) {
            ClientData.appendSrc(value);
            CommandsHandlers.askForStructure(ClientData.getSrc());
        } else {
            contentAreaReadingDialog.setText("");
            readDialogForm.pack();
            readDialogForm.setVisible(true);
            CommandsHandlers.askForOpeningFile(value);
        }
    }
    
    /**
     * This method is displaying structure of the server's files in the table
     * @param data List of strings (recived from server) containing the names of all files and directories in the current path on the server.
     */
    public void updateTable(List<String> data) {
        DefaultTableModel model = (DefaultTableModel) contentTable.getModel();

        model.setRowCount(0);

        for (String item : data) {
            String converted[] = {item, item.contains(".") ? "File" : "Folder"};
            model.addRow(converted);
        }
    }

    /**
     * This method is changing <b>path label</b> depending on the current location
     * If the path is empty (main resources server's folder), it sets "Home" name of the path.
     * @see ClientData#getSrc() <b>getSrc() - current server's path</b>
     */
    public void updateSrcLabel() {
        String value = ClientData.getSrc().isBlank() ? "Home" : ClientData.getSrc();
        src.setText(value);
    }
    
