    private void addDialogCreateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addDialogCreateBtnActionPerformed
        if (addDialogFileNameField.getText().isBlank()) {
            addDialogErrorLabel.setText("Enter name of the File/Folder");
            addDialogErrorLabel.setVisible(true);
        } else if (!addDialogFolderRadioBtn.isSelected() && !addDialogFileRadioBtn.isSelected()) {
            addDialogErrorLabel.setText("Select type of new File/Folder");
            addDialogErrorLabel.setVisible(true);
        } else {
            if (addDialogFileRadioBtn.isSelected()) {
                if (addDialogFileNameField.getText().contains(".")) {
                    CommandsHandlers.askForCreatingNewFileOrFolder(addDialogFileNameField.getText(), true);
                } else {
                    addDialogErrorLabel.setText("File must contains extension!");
                    addDialogErrorLabel.setVisible(true);
                }
            } else {
                if (!addDialogFileNameField.getText().contains(".")) {
                    CommandsHandlers.askForCreatingNewFileOrFolder(addDialogFileNameField.getText(), false);
                } else {
                    addDialogErrorLabel.setText("Folder cannot contain extension!");
                    addDialogErrorLabel.setVisible(true);
                }
            }
        }
        createFileDialog.dispose();
        CommandsHandlers.askForStructure(ClientData.getSrc());
    }//GEN-LAST:event_addDialogCreateBtnActionPerformed

