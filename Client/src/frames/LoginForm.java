    /**
     * This method is setting error label
     * @param text text to display
     * @param visible boolean if it should be visible
     */
    public void setErrorLabel(String text, boolean visible) {
        errorLabel.setText(text);
        errorLabel.setVisible(visible);
    }
    
    private void handleLogin() {
        if(Client.isProperConnection()) {
            if(loginField.getText().isBlank() || passwordField.getText().isBlank()) {
                errorLabel.setText("Enter login/password!");
                errorLabel.setVisible(true);
            }
            else {
                String login = loginField.getText();
                String password = passwordField.getText();
                CommandsHandlers.sendLoginAttempt(login, password);
            }
        }
        else {
            loginField.setEnabled(false);
            passwordField.setEnabled(false);
            setErrorLabel("There is invalid connection with server!", true);
        }
    }
    
    /**
     * This method is disabling all options in the window is setting the label for <b>invalid connection with the server</b>.<br />
     * It only shows the window that informs about invalid connection.
     */
    public void setInvalidConnectionSetting() {
        loginField.setEnabled(false);
        passwordField.setEnabled(false);
        logginBtn.setEnabled(false);
        setErrorLabel("There is invalid connection with server!", true);
    }
    
