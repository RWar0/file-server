    /**
     * This method place into the table all saved users' accounts and their data
     * @see data.DataAdministration#getUsers() <b>getUsers()</b> - list of all users
     */
    public void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) usersTable.getModel();

        model.setRowCount(0);

        for (User item : DataAdministration.getUsers()) {
            String dataForTable[] = {item.getUserId() + "", item.getLogin(), "*".repeat(item.getPassword().length()), item.getAccess() + ""};
            model.addRow(dataForTable);
        }
    }
    
    /**
     * This method append in terminal new line with given text.<br />
     * It also scrolls to the bottom of the terminal if new line placed.
     * @param text text to be placen into the terminal
     */
    public void updateTerminal(String text) {
        serverConent.append(text + "\n");
        serverConent.setCaretPosition(serverConent.getDocument().getLength());
    }

